# Примечание: коэффициенты получаем через функцию input().

print('Решаем уравнение A·x + B = 0')

A = float(input("Введите коэффициент A: "))

if A == 0:
    print('Не существуют действительных корней уравнения при A = 0')
    exit(1)

B = float(input("Введите коэффициент B: "))

print(f"Единственный корень уравнения равен {-B / A}")
